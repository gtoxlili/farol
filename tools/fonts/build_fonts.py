#!/usr/bin/env python3
"""Rebuild Farol's fonts and the Rust text metrics from pinned upstream sources.

Outputs (committed, so a normal build never needs this script):
  components/app_logic/ui/fonts/NotoSansSC-Farol.ttf   Noto Sans SC Regular cut to GB2312 + Latin;
                                                        baked by GSPC and loaded at runtime as GSP's
                                                        dynamic (FreeType) fallback font
  components/app_logic/ui/fonts/Geist*-Farol.ttf       Geist / Geist Mono cut to Latin
  rust/logic/src/text/metrics.rs                       advance widths the line breaker uses

Run from anywhere:  uv run --no-project --with fonttools python tools/fonts/build_fonts.py
Downloads go to $FAROL_FONT_CACHE (default: ~/.cache/farol-fonts) and are checked by SHA-256.
"""
from __future__ import annotations

import hashlib
import io
import os
import sys
import urllib.request
import zipfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
FONT_DIR = ROOT / "components/app_logic/ui/fonts"
METRICS_RS = ROOT / "rust/logic/src/text/metrics.rs"
CACHE = Path(os.environ.get("FAROL_FONT_CACHE", Path.home() / ".cache/farol-fonts"))

NOTO_URL = ("https://raw.githubusercontent.com/google/fonts/"
            "2894aab31764f10f29c421bdfd2340d3b382d384/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf")
NOTO_SHA256 = "a3041811a78c361b1de5"  # prefix check, see verify()
GEIST_URL = "https://github.com/vercel/geist-font/releases/download/v1.9.0/geist-font-v1.9.0.zip"
GEIST_SHA256 = "1f2dd9ea90e68d0358a1"

# Geist faces Farol uses, by role.
GEIST_FACES = {
    "Geist-Thin": "geist-font/Geist/ttf/Geist-Thin.ttf",
    "Geist-ExtraLight": "geist-font/Geist/ttf/Geist-ExtraLight.ttf",
    "Geist-Light": "geist-font/Geist/ttf/Geist-Light.ttf",
    "Geist-Regular": "geist-font/Geist/ttf/Geist-Regular.ttf",
    "Geist-Medium": "geist-font/Geist/ttf/Geist-Medium.ttf",
    "GeistMono-Regular": "geist-font/GeistMono/ttf/GeistMono-Regular.ttf",
}

# Latin text plus the punctuation and symbols the UI and agent titles commonly carry.
LATIN = (
    [chr(c) for c in range(0x20, 0x7F)]
    + list("·•…–—‘’“”′″°×÷±−→←↑↓›‹«»€£¥©®™§¶†‡№✓\u2002")
)
# CJK punctuation and fullwidth forms (all one em in Noto Sans SC).
CJK_PUNCT = [chr(c) for c in range(0x3000, 0x3040)] + [chr(c) for c in range(0xFF01, 0xFF5F)]


def fetch(url: str, sha_prefix: str) -> bytes:
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / url.rsplit("/", 1)[-1]
    if not path.exists():
        print(f"download {url}", file=sys.stderr)
        with urllib.request.urlopen(url, timeout=120) as response:
            path.write_bytes(response.read())
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if not digest.startswith(sha_prefix):
        raise SystemExit(f"{path}: sha256 {digest} does not match pinned prefix {sha_prefix}")
    return data


def gb2312_hanzi() -> list[str]:
    """Every character GB2312 encodes (symbols, kana, Greek, Cyrillic and 6763 hanzi)."""
    chars = []
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                chars.append(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return chars


def subset_font(font: TTFont, chars: list[str], out: Path) -> None:
    options = subset.Options()
    options.layout_features = ["kern", "liga", "calt"]
    options.hinting = False
    options.desubroutinize = True
    options.name_IDs = ["*"]
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=sorted({ord(c) for c in chars}))
    sub.subset(font)
    font.save(out)
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size} bytes", file=sys.stderr)


def advances(path: Path, chars: list[str]) -> tuple[int, dict[int, int]]:
    font = TTFont(path)
    upem = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    table = {}
    for ch in chars:
        cp = ord(ch)
        if cp in cmap:
            table[cp] = hmtx[cmap[cp]][0]
    return upem, table


def write_metrics(fonts: dict[str, Path]) -> None:
    lines = [
        "// @generated by tools/fonts/build_fonts.py; do not edit.",
        "//! Advance widths, in font units, of the non-ideographic characters Farol's",
        "//! line breaker measures. Ideographs and fullwidth forms are one em wide.",
        "",
    ]
    for name, path in fonts.items():
        upem, table = advances(path, LATIN + CJK_PUNCT)
        const = name.upper().replace("-", "_")
        lines.append(f"/// {name}: units per em and (codepoint, advance) pairs sorted by codepoint.")
        lines.append(f"pub const {const}_UPEM: u16 = {upem};")
        lines.append(f"pub static {const}: &[(u32, u16)] = &[")
        for cp in sorted(table):
            lines.append(f"    (0x{cp:04X}, {table[cp]}),")
        lines.append("];")
        lines.append("")
    METRICS_RS.parent.mkdir(parents=True, exist_ok=True)
    METRICS_RS.write_text("\n".join(lines))
    print(f"{METRICS_RS.relative_to(ROOT)} written", file=sys.stderr)


def main() -> None:
    FONT_DIR.mkdir(parents=True, exist_ok=True)

    noto = TTFont(io.BytesIO(fetch(NOTO_URL, NOTO_SHA256)))
    noto = instancer.instantiateVariableFont(noto, {"wght": 400})
    noto_out = FONT_DIR / "NotoSansSC-Farol.ttf"
    subset_font(noto, LATIN + CJK_PUNCT + gb2312_hanzi(), noto_out)

    archive = zipfile.ZipFile(io.BytesIO(fetch(GEIST_URL, GEIST_SHA256)))
    outputs = {"NotoSansSC": noto_out}
    for face, member in GEIST_FACES.items():
        out = FONT_DIR / f"{face}-Farol.ttf"
        subset_font(TTFont(io.BytesIO(archive.read(member))), LATIN, out)
        outputs[face] = out

    write_metrics({"NotoSansSC": outputs["NotoSansSC"]})


if __name__ == "__main__":
    main()
