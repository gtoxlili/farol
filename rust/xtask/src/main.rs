//! `cargo xtask gen-gsp`: bindgen over `gsp_sys/wrapper.h`, once for the board
//! and once for the build host, plus the C staleness check.
//!
//! Inputs come from a finished IDF build of this project: the resolved ESP-GSP
//! component and the scene headers gspc generated for app_logic. Both binding
//! files come from the same headers, so board and host agree on every constant.

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

type Result<T> = std::result::Result<T, String>;

/// Scene headers gspc writes for the scene named "app" (`"screen"` in main.json).
const SCENE_HEADERS: [&str; 3] = ["app_objects.h", "app_actions.h", "app_binds.h"];

fn main() -> ExitCode {
    let task = std::env::args().nth(1);
    let result = match task.as_deref() {
        Some("gen-gsp") => generate(),
        _ => Err("usage: cargo xtask gen-gsp".to_string()),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("xtask: {message}");
            ExitCode::FAILURE
        }
    }
}

struct Inputs {
    rust: PathBuf,
    project: PathBuf,
    gsp: PathBuf,
    scene: PathBuf,
}

fn generate() -> Result<()> {
    let rust = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .canonicalize()
        .map_err(|e| format!("rust workspace: {e}"))?;
    let project = rust.parent().unwrap_or(&rust).to_path_buf();
    let inputs = Inputs {
        gsp: project.join("managed_components/espressif__esp-gsp/include"),
        scene: project.join("build/esp-idf/app_logic/gsp_gen_bundle/scene0"),
        rust,
        project,
    };
    for required in [&inputs.gsp, &inputs.scene] {
        if !required.exists() {
            return Err(format!(
                "{} is missing; run the IDF build once first",
                required.display()
            ));
        }
    }
    let riscv_args = vec![
        "--target=riscv32-unknown-none-elf".to_string(),
        "-mabi=ilp32f".to_string(),
        format!("-isystem{}", picolibc_include()?.display()),
    ];
    write_bindings(&inputs, "bindings_riscv32.rs", &riscv_args)?;
    write_bindings(&inputs, "bindings_host.rs", &host_args()?)?;
    write_staleness_check(
        &inputs.scene,
        &inputs
            .project
            .join("components/app_logic/gsp_bindings_check.h"),
    )
}

fn write_bindings(inputs: &Inputs, file: &str, target_args: &[String]) -> Result<()> {
    let out = inputs.rust.join("gsp_sys/src").join(file);
    let bindings = bindgen::Builder::default()
        .header(inputs.rust.join("gsp_sys/wrapper.h").to_string_lossy())
        .clang_arg(format!("-I{}", inputs.gsp.display()))
        .clang_arg(format!("-I{}", inputs.scene.display()))
        .clang_args(target_args)
        .use_core()
        .ctypes_prefix("core::ffi")
        .allowlist_function("esp_gsp_.*")
        .allowlist_type("esp_gsp_.*|gsp_value_t|gsp_component_key_t|gsp_property_key_t")
        .allowlist_var(
            "ESP_GSP_.*|GSP_OBJ_KEY_.*|GSP_PROP_KEY_.*|GSP_ACT_ID_.*|GSP_BIND_.*|GSP_VALUE_.*",
        )
        .default_enum_style(bindgen::EnumVariation::Consts)
        .prepend_enum_name(false)
        .derive_default(true)
        .layout_tests(false)
        .generate_comments(false)
        .formatter(bindgen::Formatter::Prettyplease)
        .generate()
        .map_err(|e| format!("bindgen ({file}): {e}"))?;
    bindings
        .write_to_file(&out)
        .map_err(|e| format!("write {}: {e}", out.display()))?;
    println!("wrote {}", out.display());
    Ok(())
}

/// Records the scene constants the bindings were generated from as C static
/// assertions. The device build (app_logic.c) and the simulator backend
/// (host/platform_pc.c) include it next to their live gspc headers, so a scene
/// edit without `cargo xtask gen-gsp` fails both builds.
fn write_staleness_check(scene: &Path, out: &Path) -> Result<()> {
    let mut text =
        String::from("/* Generated by `cargo xtask gen-gsp`; do not edit. */\n#pragma once\n\n");
    let tracked = ["GSP_OBJ_KEY_", "GSP_BIND_", "GSP_ACT_ID_", "GSP_PROP_KEY_"];
    for header in SCENE_HEADERS {
        let path = scene.join(header);
        let source =
            std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        for line in source.lines() {
            let mut words = line.split_whitespace();
            let (Some("#define"), Some(name), Some(value), None) =
                (words.next(), words.next(), words.next(), words.next())
            else {
                continue;
            };
            if tracked.iter().any(|prefix| name.starts_with(prefix)) {
                text.push_str(&format!(
                    "_Static_assert({name} == {value}, \"stale Rust GSP bindings: run cargo xtask gen-gsp\");\n"
                ));
            }
        }
    }
    std::fs::write(out, text).map_err(|e| format!("write {}: {e}", out.display()))?;
    println!("wrote {}", out.display());
    Ok(())
}

/// Picolibc headers shipped with the IDF RISC-V toolchain (`$IDF_TOOLS_PATH`).
fn picolibc_include() -> Result<PathBuf> {
    let tools =
        std::env::var("IDF_TOOLS_PATH").map_err(|_| "IDF_TOOLS_PATH is not set".to_string())?;
    let root = Path::new(&tools).join("tools/riscv32-esp-elf");
    let mut versions: Vec<_> = std::fs::read_dir(&root)
        .map_err(|e| format!("{}: {e}", root.display()))?
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .collect();
    versions.sort();
    versions
        .into_iter()
        .rev()
        .map(|v| v.join("riscv32-esp-elf/picolibc/include"))
        .find(|p| p.is_dir())
        .ok_or_else(|| format!("no picolibc headers under {}", root.display()))
}

/// Clang's default target is the build host; on macOS it also needs the SDK.
fn host_args() -> Result<Vec<String>> {
    if !cfg!(target_os = "macos") {
        return Ok(Vec::new());
    }
    let output = Command::new("xcrun")
        .args(["--show-sdk-path"])
        .output()
        .map_err(|e| format!("xcrun --show-sdk-path: {e}"))?;
    if !output.status.success() {
        return Err("xcrun --show-sdk-path failed; install the Xcode command line tools".into());
    }
    let sdk = String::from_utf8_lossy(&output.stdout).trim().to_string();
    Ok(vec![format!("-isysroot{sdk}")])
}
